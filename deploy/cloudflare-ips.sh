#!/usr/bin/env bash
# Trust Cloudflare's proxy, once the DNS records are proxied (orange cloud). Run as root:
#   sudo /opt/ravenx/deploy/cloudflare-ips.sh
# - nginx takes the visitor's IP from CF-Connecting-IP, but only on requests from Cloudflare,
#   so rate limits and logs are per visitor rather than per Cloudflare server.
# - ufw accepts ports 80/443 from Cloudflare only; SSH stays open.
# A monthly cron job reruns it to follow changes to Cloudflare's ranges.
set -euo pipefail

CONF=/etc/nginx/conf.d/cloudflare-realip.conf
TAG=cloudflare

ranges=$( { curl -fsS --max-time 20 https://www.cloudflare.com/ips-v4; echo
            curl -fsS --max-time 20 https://www.cloudflare.com/ips-v6; echo; } \
          | grep -E '^[0-9a-fA-F:.]+/[0-9]+$' )
count=$(grep -c . <<<"$ranges")
# Never apply a partial list: it would lock out part of Cloudflare (they publish ~22 ranges)
if [ "$count" -lt 10 ]; then
    echo "Only $count ranges fetched from Cloudflare; nothing changed" >&2
    exit 1
fi

# nginx real IP
{
    echo "# Generated by /opt/ravenx/deploy/cloudflare-ips.sh — do not edit"
    while read -r r; do echo "set_real_ip_from $r;"; done <<<"$ranges"
    echo "real_ip_header CF-Connecting-IP;"
} > "$CONF.new"
[ -f "$CONF" ] && cp "$CONF" "$CONF.bak"
mv "$CONF.new" "$CONF"
if ! nginx -t -q; then
    if [ -f "$CONF.bak" ]; then mv "$CONF.bak" "$CONF"; else rm -f "$CONF"; fi
    echo "nginx rejected the config; previous one restored" >&2
    exit 1
fi
rm -f "$CONF.bak"
systemctl reload nginx

# Firewall: add the current ranges first, then drop stale ones and the open-to-all rules
while read -r r; do
    ufw allow proto tcp from "$r" to any port 80,443 comment "$TAG" >/dev/null
done <<<"$ranges"
ufw show added \
    | sed -n "s/^ufw allow proto tcp from \([^ ]*\) to any port 80,443 comment '$TAG'\$/\1/p" \
    | while read -r old; do
        grep -qxF "$old" <<<"$ranges" || ufw delete allow proto tcp from "$old" to any port 80,443 >/dev/null
      done
for rule in 80/tcp 443/tcp "Nginx Full"; do
    ufw delete allow "$rule" >/dev/null 2>&1 || true
done

echo "Cloudflare: $count ranges applied to nginx and ufw"
