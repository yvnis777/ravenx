'use client'
import { useState, useEffect } from 'react'
import { useMutation, useQueryClient } from '@tanstack/react-query'
import { api } from '@/lib/api'
import { assertBackendNetwork } from '@/lib/hl-env'
import { useAuth } from '@/hooks/useAuth'
import { useSubscriptions } from '@/hooks/useSubscriptions'
import { useAgentApproval, BUILDER_ADDRESS, feeRateLabel } from '@/hooks/useAgentApproval'
import { useAppKit } from '@reown/appkit/react'
import { Button } from '@/components/ui/Button'
import { Badge } from '@/components/ui/Badge'
import { Spinner } from '@/components/ui/Spinner'
import type { Subscription } from '@/types'

const COPY_ERRORS: Record<string, string> = {
  'Agent is not approved on Hyperliquid for this account':
    'Agent approval did not register on Hyperliquid. Try again or check your wallet.',
  'Agent not generated by this server (or expired). Please retry the copy flow from the beginning.':
    'Agent expired. Please start the flow again.',
  'target_address and agent_address required': 'Missing trader. Refresh and try again.',
}

function mapCopyError(raw: string): string {
  if (raw.includes('fee') && raw.includes('not approved')) {
    return `The RavenX fee (${feeRateLabel()}) was not approved on Hyperliquid. Try again.`
  }
  return COPY_ERRORS[raw] ?? raw ?? 'Failed to start copying. Try again.'
}

function formatRiskSummary(sub: Subscription): string {
  const rp = sub.risk_params ?? {}
  const parts: string[] = [`Scale ${sub.scaling_pct}%`]
  if (rp.stop_loss_pct) parts.push(`SL ${rp.stop_loss_pct}%`)
  if (rp.max_drawdown_pct) parts.push(`DD ${rp.max_drawdown_pct}%`)
  if (rp.max_position_usd) parts.push(`Max $${rp.max_position_usd}`)
  if (rp.price_tolerance_pct === -1) parts.push('Market orders')
  else if (rp.price_tolerance_pct) parts.push(`±${rp.price_tolerance_pct}%`)
  return parts.join(' · ')
}

const LABEL = 'text-[10px] uppercase tracking-wider text-faint'
const FIELD =
  'num h-[26px] rounded-md border border-line bg-raised px-2 text-xs text-fg ' +
  'placeholder:text-faint outline-none transition-colors focus:border-accent'

function Segmented<T extends string>({
  options,
  value,
  onChange,
}: {
  options: { key: T; label: string }[]
  value: T
  onChange: (v: T) => void
}) {
  return (
    <div className="flex gap-0.5 rounded-md border border-line bg-raised p-0.5">
      {options.map(({ key, label }) => (
        <button
          key={key}
          type="button"
          onClick={() => onChange(key)}
          aria-pressed={value === key}
          className={`flex-1 rounded px-2 py-1 text-[11px] transition-colors ${
            value === key ? 'bg-accent-dim text-accent' : 'text-faint hover:text-fg'
          }`}
        >
          {label}
        </button>
      ))}
    </div>
  )
}

function Toggle({
  checked,
  onChange,
  label,
}: {
  checked: boolean
  onChange: (v: boolean) => void
  label: string
}) {
  return (
    <button
      role="switch"
      type="button"
      aria-checked={checked}
      aria-label={label}
      onClick={() => onChange(!checked)}
      className={`h-[14px] w-[26px] flex-shrink-0 rounded-sm border transition-colors ${
        checked ? 'border-accent bg-accent-dim' : 'border-line bg-raised'
      }`}
    >
      <span
        className={`block h-[10px] w-[10px] rounded-[1px] transition-transform ${
          checked ? 'translate-x-[13px] bg-accent' : 'translate-x-[1px] bg-faint'
        }`}
      />
    </button>
  )
}

interface CopyModalProps {
  targetAddress: string
  onClose: () => void
}

export function CopyModal({ targetAddress, onClose }: CopyModalProps) {
  const { isAuthenticated } = useAuth()
  const { open } = useAppKit()
  const queryClient = useQueryClient()
  const { data: subscriptions = [] } = useSubscriptions()
  const { approve, step } = useAgentApproval()

  const [scalingPct, setScalingPct] = useState(100)
  const [stopLossEnabled, setStopLossEnabled] = useState(false)
  const [stopLoss, setStopLoss] = useState('10')
  const [maxDrawdownEnabled, setMaxDrawdownEnabled] = useState(false)
  const [maxDrawdown, setMaxDrawdown] = useState('20')
  const [maxPositionEnabled, setMaxPositionEnabled] = useState(false)
  const [maxPosition, setMaxPosition] = useState('5000')
  const [priceMode, setPriceMode] = useState<'default' | 'tolerance' | 'market'>('default')
  const [priceTolerance, setPriceTolerance] = useState('0.5')
  const [copyExistingMode, setCopyExistingMode] = useState<'none' | 'favorable' | 'market'>('none')
  const [showAdvanced, setShowAdvanced] = useState(false)
  const [editing, setEditing] = useState(false)
  const [error, setError] = useState('')
  const [statusMsg, setStatusMsg] = useState('')
  const [targetName, setTargetName] = useState('')

  const activeSub = subscriptions.find(
    (s) => s.target_address.toLowerCase() === targetAddress.toLowerCase() && s.is_active
  )
  const activeSubs = subscriptions.filter((s) => s.is_active)
  const cumulativeScaling = activeSubs.reduce((sum, s) => sum + s.scaling_pct, 0) + scalingPct
  const overCap = !activeSub && cumulativeScaling > 100
  const activeCount = activeSubs.length

  useEffect(() => {
    function onKey(e: KeyboardEvent) {
      if (e.key === 'Escape') onClose()
    }
    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [onClose])

  function enterEditMode() {
    if (!activeSub) return
    const rp = activeSub.risk_params ?? {}
    setScalingPct(activeSub.scaling_pct)
    setTargetName(activeSub.target_name ?? '')
    setStopLossEnabled(!!rp.stop_loss_pct)
    setStopLoss(String(rp.stop_loss_pct ?? 10))
    setMaxDrawdownEnabled(!!rp.max_drawdown_pct)
    setMaxDrawdown(String(rp.max_drawdown_pct ?? 20))
    setMaxPositionEnabled(!!rp.max_position_usd)
    setMaxPosition(String(rp.max_position_usd ?? 5000))
    const tol = rp.price_tolerance_pct
    if (tol === -1) setPriceMode('market')
    else if (tol != null && tol > 0) {
      setPriceMode('tolerance')
      setPriceTolerance(String(tol))
    } else setPriceMode('default')
    setError('')
    setEditing(true)
  }

  function buildRiskParams() {
    return {
      ...(stopLossEnabled ? { stop_loss_pct: Number(stopLoss) } : {}),
      ...(maxDrawdownEnabled ? { max_drawdown_pct: Number(maxDrawdown) } : {}),
      ...(maxPositionEnabled ? { max_position_usd: Number(maxPosition) } : {}),
      ...(priceMode === 'market'
        ? { price_tolerance_pct: -1 }
        : priceMode === 'tolerance'
          ? { price_tolerance_pct: Number(priceTolerance) }
          : {}),
      ...(copyExistingMode !== 'none' ? { copy_existing_mode: copyExistingMode } : {}),
    }
  }

  const startMutation = useMutation({
    mutationFn: async () => {
      await assertBackendNetwork()
      const agentAddress = await approve()
      const { data } = await api.post('/copy/start', {
        target_address: targetAddress,
        agent_address: agentAddress,
        scaling_pct: scalingPct,
        risk_params: buildRiskParams(),
        target_name: targetName.trim() || undefined,
      })
      return data
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['subscriptions'] })
      setStatusMsg('Copy trading started.')
      onClose()
    },
    onError: (e: unknown) => {
      const err = e as { message?: string; response?: { data?: { error?: string } } }
      setError(
        err?.response?.data?.error
          ? mapCopyError(err.response.data.error)
          : (err?.message ?? 'Failed to start copying.')
      )
    },
  })

  const editMutation = useMutation({
    mutationFn: () =>
      api.patch(`/copy/subscriptions/${activeSub?.id}`, {
        scaling_pct: scalingPct,
        risk_params: buildRiskParams(),
        target_name: targetName.trim() || null,
      }),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['subscriptions'] })
      setEditing(false)
      setError('')
      setStatusMsg('Settings saved.')
      setTimeout(() => setStatusMsg(''), 3000)
    },
    onError: (e: unknown) => {
      const err = e as { response?: { data?: { error?: string } } }
      setError(err?.response?.data?.error ?? 'Failed to update settings')
    },
  })

  const stopMutation = useMutation({
    mutationFn: () => api.post('/copy/stop', { subscription_id: activeSub?.id }),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['subscriptions'] })
      onClose()
    },
    onError: (e: unknown) => {
      const err = e as { response?: { data?: { error?: string } } }
      setError(err?.response?.data?.error ?? 'Failed to stop copying')
    },
  })

  const truncated = `${targetAddress.slice(0, 6)}…${targetAddress.slice(-4)}`
  const hasCustomSettings =
    priceMode !== 'default' || stopLossEnabled || maxDrawdownEnabled || maxPositionEnabled

  const stepMessage =
    step.kind === 'awaiting-fee-signature'
      ? `Approve the ${feeRateLabel()} RavenX fee in your wallet — signature 1 of 2`
      : step.kind === 'submitting-fee'
        ? 'Submitting fee approval to Hyperliquid…'
        : step.kind === 'generating'
          ? 'Generating agent wallet…'
          : step.kind === 'awaiting-signature'
            ? `Approve agent ${step.agentAddress.slice(0, 10)}… in your wallet${
                BUILDER_ADDRESS ? ' — signature 2 of 2' : ''
              }`
            : step.kind === 'submitting'
              ? 'Submitting agent approval to Hyperliquid…'
              : ''

  const settingsForm = (
    <>
      <div className="flex flex-col gap-1">
        <label className={LABEL} htmlFor="copy-name">
          Label (optional)
        </label>
        <input
          id="copy-name"
          type="text"
          value={targetName}
          onChange={(e) => setTargetName(e.target.value)}
          placeholder="e.g. Top BTC trader"
          maxLength={100}
          className={`${FIELD} w-full`}
        />
      </div>

      <div className="flex flex-col gap-1">
        <div className="flex items-center justify-between">
          <span className={LABEL}>Scale</span>
          <span className="num text-xs font-medium text-accent">{scalingPct}%</span>
        </div>
        <input
          type="range"
          min={10}
          max={200}
          step={10}
          value={scalingPct}
          onChange={(e) => setScalingPct(Number(e.target.value))}
          aria-label="Scaling percent"
          className="w-full accent-[var(--accent)]"
        />
        <p className="text-[11px] text-faint">
          100% mirrors the trader&apos;s sizing, proportional to your equity.
        </p>
      </div>

      <button
        type="button"
        onClick={() => setShowAdvanced(!showAdvanced)}
        className="flex items-center gap-1.5 text-[11px] text-faint transition-colors hover:text-muted"
        aria-expanded={showAdvanced}
      >
        <span aria-hidden="true">{showAdvanced ? '▾' : '▸'}</span>
        Advanced
        {hasCustomSettings && <span className="text-accent">●</span>}
      </button>

      {showAdvanced && (
        <div className="flex flex-col gap-4 animate-slide-up">
          <div className="flex flex-col gap-1.5">
            <span className={LABEL}>Entry price</span>
            <Segmented
              value={priceMode}
              onChange={setPriceMode}
              options={[
                { key: 'default', label: 'Same or better' },
                { key: 'tolerance', label: 'Tolerance' },
                { key: 'market', label: 'Market' },
              ]}
            />
            {priceMode === 'tolerance' && (
              <div className="flex items-center gap-2">
                <input
                  type="number"
                  value={priceTolerance}
                  onChange={(e) => setPriceTolerance(e.target.value)}
                  onBlur={() => {
                    const v = Number(priceTolerance)
                    if (v < 0.1) setPriceTolerance('0.1')
                    if (v > 10) setPriceTolerance('10')
                  }}
                  min={0.1}
                  max={10}
                  step={0.1}
                  aria-label="Price tolerance percent"
                  className={`${FIELD} w-16 text-right`}
                />
                <span className="text-[11px] text-faint">% worse than trader&apos;s entry</span>
              </div>
            )}
            {priceMode === 'market' && (
              <p className="text-[11px] text-warn">Market orders execute at any price.</p>
            )}
          </div>

          <div className="flex flex-col gap-1.5">
            <span className={LABEL}>Existing positions</span>
            <Segmented
              value={copyExistingMode}
              onChange={setCopyExistingMode}
              options={[
                { key: 'none', label: 'New only' },
                { key: 'favorable', label: 'If better' },
                { key: 'market', label: 'At market' },
              ]}
            />
          </div>

          <div className="flex flex-col gap-2">
            <span className={LABEL}>Risk controls</span>

            <div className="flex items-center gap-2">
              <Toggle checked={stopLossEnabled} onChange={setStopLossEnabled} label="Stop loss" />
              <span className="flex-1 text-xs text-muted">Stop loss</span>
              {stopLossEnabled && (
                <div className="flex items-center gap-1">
                  <input
                    type="number"
                    value={stopLoss}
                    onChange={(e) => setStopLoss(e.target.value)}
                    min={0.1}
                    max={100}
                    aria-label="Stop loss percent"
                    className={`${FIELD} w-14 text-right`}
                  />
                  <span className="text-[11px] text-faint">%</span>
                </div>
              )}
            </div>

            <div className="flex items-center gap-2">
              <Toggle
                checked={maxDrawdownEnabled}
                onChange={setMaxDrawdownEnabled}
                label="Max drawdown"
              />
              <span className="flex-1 text-xs text-muted">Max drawdown</span>
              {maxDrawdownEnabled && (
                <div className="flex items-center gap-1">
                  <input
                    type="number"
                    value={maxDrawdown}
                    onChange={(e) => setMaxDrawdown(e.target.value)}
                    min={0.1}
                    max={100}
                    aria-label="Max drawdown percent"
                    className={`${FIELD} w-14 text-right`}
                  />
                  <span className="text-[11px] text-faint">%</span>
                </div>
              )}
            </div>

            <div className="flex items-center gap-2">
              <Toggle
                checked={maxPositionEnabled}
                onChange={setMaxPositionEnabled}
                label="Max position"
              />
              <span className="flex-1 text-xs text-muted">Max position</span>
              {maxPositionEnabled && (
                <div className="flex items-center gap-1">
                  <span className="text-[11px] text-faint">$</span>
                  <input
                    type="number"
                    value={maxPosition}
                    onChange={(e) => setMaxPosition(e.target.value)}
                    min={1}
                    max={1000000}
                    aria-label="Max position in dollars"
                    className={`${FIELD} w-20 text-right`}
                  />
                </div>
              )}
            </div>
          </div>
        </div>
      )}
    </>
  )

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-black/70 p-4"
      onClick={onClose}
    >
      <div
        role="dialog"
        aria-modal="true"
        aria-label="Copy trader settings"
        className="modal flex max-h-[88vh] w-full max-w-[420px] flex-col rounded-md"
        onClick={(e) => e.stopPropagation()}
      >
        <header className="flex flex-shrink-0 items-center gap-2 border-b border-line px-3 h-[38px]">
          <h2 className="text-[13px] font-semibold text-fg">Copy trader</h2>
          <span className="num text-[11px] text-faint">{truncated}</span>
          <button
            onClick={onClose}
            aria-label="Close"
            className="ml-auto text-base leading-none text-faint transition-colors hover:text-fg"
          >
            ×
          </button>
        </header>

        <div className="flex flex-col gap-4 overflow-y-auto p-3">
          <p className="sr-only" aria-live="assertive" aria-atomic="true">
            {statusMsg}
          </p>

          {!isAuthenticated ? (
            <div className="flex flex-col items-center gap-3 py-6">
              <p className="text-xs text-muted">Connect your wallet to start copy-trading.</p>
              <Button
                size="sm"
                onClick={() => {
                  open()
                  onClose()
                }}
              >
                Connect wallet
              </Button>
            </div>
          ) : activeSub && !editing ? (
            <>
              <div className="flex items-start justify-between gap-2 rounded-md border border-line bg-raised p-3">
                <div className="flex flex-col gap-1">
                  <Badge variant="profit">Active</Badge>
                  <p className="text-[11px] text-muted">{formatRiskSummary(activeSub)}</p>
                  <p className="num text-[11px] text-faint">
                    Agent {activeSub.agent_address.slice(0, 6)}…{activeSub.agent_address.slice(-4)}
                  </p>
                </div>
                <Button size="sm" variant="secondary" onClick={enterEditMode}>
                  Edit
                </Button>
              </div>
              {error && <p className="text-xs text-loss">{error}</p>}
              <div className="flex justify-end">
                <Button
                  variant="danger"
                  size="sm"
                  onClick={() => {
                    setError('')
                    stopMutation.mutate()
                  }}
                  disabled={stopMutation.isPending}
                >
                  {stopMutation.isPending ? <Spinner size="sm" /> : 'Stop copying'}
                </Button>
              </div>
            </>
          ) : activeSub && editing ? (
            <>
              <p className="text-[11px] text-faint">
                Editing an active copy — changes take effect immediately.
              </p>
              {settingsForm}
              {error && <p className="text-xs text-loss">{error}</p>}
              <div className="flex gap-2">
                <Button
                  variant="danger"
                  size="sm"
                  onClick={() => {
                    setError('')
                    stopMutation.mutate()
                  }}
                  disabled={stopMutation.isPending}
                >
                  {stopMutation.isPending ? <Spinner size="sm" /> : 'Stop'}
                </Button>
                <Button
                  variant="ghost"
                  size="sm"
                  className="ml-auto"
                  onClick={() => {
                    setEditing(false)
                    setError('')
                  }}
                >
                  Cancel
                </Button>
                <Button
                  size="sm"
                  onClick={() => {
                    setError('')
                    editMutation.mutate()
                  }}
                  disabled={editMutation.isPending}
                >
                  {editMutation.isPending ? <Spinner size="sm" /> : 'Save'}
                </Button>
              </div>
            </>
          ) : (
            <>
              {settingsForm}

              {overCap && (
                <div className="rounded-md border border-[rgba(240,180,41,0.3)] bg-[rgba(240,180,41,0.08)] p-2.5">
                  <p className="num text-xs font-medium text-warn">
                    Combined scaling {Math.round(cumulativeScaling)}%
                  </p>
                  <p className="mt-0.5 text-[11px] text-muted">
                    You have {activeCount} active {activeCount === 1 ? 'copy' : 'copies'}. Your
                    account could be over-allocated if every target invests fully.
                  </p>
                </div>
              )}

              {stepMessage && <p className="text-[11px] text-accent">{stepMessage}</p>}
              {error && <p className="text-xs text-loss">{error}</p>}

              <div className="flex gap-2">
                <Button variant="ghost" size="sm" className="flex-1" onClick={onClose}>
                  Cancel
                </Button>
                <Button
                  size="sm"
                  className="flex-1"
                  onClick={() => {
                    setError('')
                    startMutation.mutate()
                  }}
                  disabled={startMutation.isPending}
                >
                  {startMutation.isPending ? (
                    <span className="flex items-center justify-center gap-1.5">
                      <Spinner size="sm" /> Starting…
                    </span>
                  ) : (
                    'Start copying'
                  )}
                </Button>
              </div>
            </>
          )}
        </div>
      </div>
    </div>
  )
}
