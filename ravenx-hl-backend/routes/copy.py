import logging
import threading
from datetime import datetime

from flask import Blueprint, current_app as _app, jsonify, request
from flask_jwt_extended import get_jwt_identity, jwt_required

import hl_env
from extensions import db
from models.subscription import Subscription
from models.user import ParentWallet
from monitoring.websocket_manager import WebSocketManager
from services.agent_service import (
    PendingAgentNotFound, get_exchange, pop_pending_pkey, verify_agent_approved,
    verify_builder_fee_approved,
)
from services.notification_service import notify_copy_started, notify_copy_stopped

logger = logging.getLogger(__name__)
copy_bp = Blueprint("copy", __name__)


@copy_bp.route("/start", methods=["POST"])
@jwt_required()
def start_copying():
    parent = get_jwt_identity().lower()
    body = request.get_json() or {}

    target_address = (body.get("target_address") or "").strip().lower()
    agent_address = (body.get("agent_address") or "").strip().lower()

    if not target_address or not agent_address:
        return jsonify({"error": "target_address and agent_address required"}), 400

    try:
        scaling_pct = float(body.get("scaling_pct", 100.0))
    except (TypeError, ValueError):
        return jsonify({"error": "scaling_pct must be a number"}), 400
    if scaling_pct <= 0 or scaling_pct > 1000:
        return jsonify({"error": "scaling_pct must be between 0 and 1000"}), 400

    risk_params = body.get("risk_params") or {}
    if not isinstance(risk_params, dict):
        return jsonify({"error": "risk_params must be a JSON object"}), 400

    target_name = (body.get("target_name") or "").strip()[:100] or None

    # Verify the user actually approved this agent on HL
    if not verify_agent_approved(parent, agent_address):
        return jsonify({"error": "Agent is not approved on Hyperliquid for this account"}), 400

    # Verify the builder fee is approved, or the copy engine's orders would be
    # rejected by HL on the first fill rather than here.
    builder = _app.config.get("BUILDER_ADDRESS")
    if builder:
        required = int(_app.config.get("BUILDER_FEE_TENTHS_BPS", 0))
        if not verify_builder_fee_approved(parent, builder, required):
            rate = f"{required / 1000:g}%"
            return jsonify({
                "error": f"RavenX fee ({rate}) is not approved on Hyperliquid for this account"
            }), 400

    # "New only": remember what the target already holds so the engine never
    # opens it. If HL can't tell us, refuse rather than copy everything.
    copy_existing_mode = risk_params.get("copy_existing_mode", "none")
    held_at_start = None
    if copy_existing_mode == "none":
        try:
            from services.copy_service import _get_state
            target_pos, _ = _get_state(target_address)
        except Exception as e:
            logger.warning("Could not read target %s positions: %s", target_address, e)
            return jsonify({
                "error": "Couldn't read this wallet's positions from Hyperliquid. Please try again."
            }), 502
        held_at_start = {coin: 1 if p["szi"] > 0 else -1 for coin, p in target_pos.items()}

    # Pop the cached private key (consumes the pending entry)
    try:
        agent_pkey = pop_pending_pkey(agent_address, parent)
    except PendingAgentNotFound:
        return jsonify({
            "error": "Agent not generated by this server (or expired). "
                     "Please retry the copy flow from the beginning."
        }), 400

    if not db.session.get(ParentWallet, parent):
        db.session.add(ParentWallet(address=parent))
        db.session.commit()

    # Snapshot peak equity from parent's HL account
    peak_equity = None
    try:
        from hyperliquid.info import Info
        info = Info(hl_env.API_URL, skip_ws=True)
        state = info.user_state(parent)
        peak_equity = float(state["marginSummary"]["accountValue"])
    except Exception:
        pass

    sub = Subscription(
        parent_address=parent,
        agent_address=agent_address,
        agent_private_key=agent_pkey,
        target_address=target_address,
        target_name=target_name,
        scaling_pct=scaling_pct,
        is_active=True,
        risk_params=risk_params,
        peak_equity=peak_equity,
        held_at_start=held_at_start,
    )
    db.session.add(sub)
    db.session.commit()

    WebSocketManager.get_instance().subscribe(target_address)

    # Optional initial sync
    if copy_existing_mode != "none":
        flask_app = _app._get_current_object()
        sub_id = sub.id
        rp = dict(risk_params or {})
        if copy_existing_mode == "market":
            rp["price_tolerance_pct"] = -1
        elif copy_existing_mode == "favorable":
            rp.pop("price_tolerance_pct", None)

        def _initial_sync(app=flask_app, sub_id=sub_id, rp=rp,
                          parent=parent, pkey=agent_pkey,
                          target=target_address, scaling=scaling_pct):
            from services.copy_service import execute_copy
            with app.app_context():
                try:
                    execute_copy(sub_id, parent, pkey, target, scaling, rp)
                except Exception as e:
                    logger.warning("Initial sync failed: %s", e)
                    db.session.rollback()
        threading.Thread(target=_initial_sync, daemon=True).start()

    try:
        notify_copy_started(parent, target_address)
    except Exception:
        pass

    return jsonify(sub.to_dict()), 201


@copy_bp.route("/stop", methods=["POST"])
@jwt_required()
def stop_copying():
    parent = get_jwt_identity().lower()
    sub_id = (request.get_json() or {}).get("subscription_id")
    if not sub_id:
        return jsonify({"error": "subscription_id required"}), 400

    sub = db.session.get(Subscription, sub_id)
    if not sub or sub.parent_address.lower() != parent:
        return jsonify({"error": "Subscription not found"}), 404

    sub.is_active = False
    sub.stopped_at = datetime.utcnow()
    db.session.commit()

    # Cancel any of this sub's orders still open on the parent's account
    if sub.agent_private_key:
        flask_app = _app._get_current_object()
        parent_addr = sub.parent_address
        agent_pkey = sub.agent_private_key
        sub_id_capture = sub.id

        def _cancel_all(app=flask_app, addr=parent_addr, pkey=agent_pkey,
                        sid=sub_id_capture):
            with app.app_context():
                try:
                    from hyperliquid.info import Info
                    from hyperliquid.utils import signing
                    from services.copy_service import _cloid_belongs_to_sub
                    inf = Info(hl_env.API_URL, skip_ws=True)
                    open_orders = inf.open_orders(addr)
                    # Filter by cloid so we don't cancel other subs' orders
                    mine = [o for o in open_orders
                            if _cloid_belongs_to_sub(o.get("cloid"), sid)]
                    if mine:
                        exchange = get_exchange(addr, pkey)
                        reqs = [signing.CancelRequest(coin=o["coin"], oid=o["oid"])
                                for o in mine]
                        exchange.bulk_cancel(reqs)
                        logger.info("Cancelled %d order(s) on stop for sub=%d %s",
                                    len(reqs), sid, addr)
                except Exception as e:
                    logger.warning("Could not cancel orders on stop for %s: %s", addr, e)
        threading.Thread(target=_cancel_all, daemon=True).start()

    try:
        notify_copy_stopped(sub.parent_address, sub.target_address)
    except Exception:
        pass

    from services.copy_service import release_sub_lock
    release_sub_lock(sub_id)

    remaining = Subscription.query.filter_by(
        target_address=sub.target_address, is_active=True
    ).count()
    if remaining == 0:
        WebSocketManager.get_instance().unsubscribe(sub.target_address)

    return jsonify(sub.to_dict())


@copy_bp.route("/subscriptions", methods=["GET"])
@jwt_required()
def list_subscriptions():
    parent = get_jwt_identity().lower()
    subs = Subscription.query.filter_by(parent_address=parent).all()
    return jsonify([s.to_dict() for s in subs])


@copy_bp.route("/subscriptions/<int:sub_id>", methods=["PATCH"])
@jwt_required()
def update_subscription(sub_id: int):
    parent = get_jwt_identity().lower()
    body = request.get_json() or {}

    sub = db.session.get(Subscription, sub_id)
    if not sub or sub.parent_address.lower() != parent:
        return jsonify({"error": "Subscription not found"}), 404

    if "scaling_pct" in body:
        try:
            val = float(body["scaling_pct"])
        except (TypeError, ValueError):
            return jsonify({"error": "scaling_pct must be a number"}), 400
        if val <= 0 or val > 1000:
            return jsonify({"error": "scaling_pct must be between 0 and 1000"}), 400
        sub.scaling_pct = val
    if "risk_params" in body:
        if not isinstance(body["risk_params"], dict):
            return jsonify({"error": "risk_params must be a JSON object"}), 400
        sub.risk_params = body["risk_params"]
    if "target_name" in body:
        sub.target_name = (body["target_name"] or "").strip()[:100] or None

    db.session.commit()
    return jsonify(sub.to_dict())
